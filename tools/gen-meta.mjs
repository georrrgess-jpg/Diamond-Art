// Precompute gallery metadata (gem counts, palettes) so the gallery opens instantly.
// Run after changing any artwork: node tools/gen-meta.mjs
import { writeFileSync } from 'node:fs';
globalThis.document = {};
const root = new URL('../js/', import.meta.url);
const A = await import(new URL('artworks.js', root));
await import(new URL('collection2.js', root));
const meta = {};
for (const m of A.CATALOG) {
  const a = A.getArtwork(m.id);
  meta[m.id] = { v: m.version, n: a.sockets.length, pal: a.palette.map((p) => p.key) };
}
writeFileSync(new URL('meta.js', root), '// Generated by tools/gen-meta.mjs. Do not edit.\nexport const META = ' + JSON.stringify(meta) + ';\n');
console.log('wrote js/meta.js for', Object.keys(meta).length, 'artworks');
